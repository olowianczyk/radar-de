// Regenerates api/_sources.js (the cron's default scan set) from the single
// source of truth, app/src/workspaces.js. Run after editing any workspace's
// sources:  node scripts/sync-sources.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { WORKSPACES } from "../app/src/workspaces.js";

const out = {};
for (const ws of WORKSPACES) {
  out[ws.id] = ws.sources
    .filter((s) => s.kind !== "manual" && (s.keyword || s.title))
    .map((s) => {
      const o = { id: s.id };
      if (s.keyword) o.keyword = s.keyword;
      if (s.title) o.title = s.title;
      if (s.publisher && s.publisher !== "DU") o.publisher = s.publisher;
      if (s.active === false) o.active = false;
      return o;
    });
}
const header = "// GENERATED by scripts/sync-sources.mjs from app/src/workspaces.js — do not edit.\n// Default per-workspace scan set for the daily cron (see api/scan-all.js).\n";
const body = "module.exports = " + JSON.stringify(out, null, 2).replace(/"([a-z]+)":/g, "$1:") + ";\n";
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "api", "_sources.js");
writeFileSync(target, header + body);
console.log("wrote", target, Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
