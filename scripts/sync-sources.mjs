// Regenerates api/_sources.js (the cron's default scan set) from the single
// source of truth, app/src/workspaces.js. Run after editing any workspace's
// sources:  node scripts/sync-sources.mjs
// Also writes server/php/sources.json — the same set for the PHP port (SEOHOST).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { WORKSPACES_PL, WORKSPACES_DE } from "../app/src/workspaces.js";

// Builds { workspaceId: [source,...] } for one country's workspace list.
function build(list) {
const out = {};
for (const ws of list) {
  out[ws.id] = ws.sources
    .filter((s) => s.kind !== "manual" && (s.keyword || s.title || (s.register === "SAOS" && (s.referencedRegulation || s.phrase)) || (s.register === "RIPCASE" && s.court) || (s.register === "BAGRSS" && s.feed)))
    .map((s) => {
      const o = { id: s.id };
      if (s.keyword) o.keyword = s.keyword;
      if (s.title) o.title = s.title;
      if (s.publisher && s.publisher !== "DU") o.publisher = s.publisher;
      if (s.register === "SAOS") { o.register = "SAOS"; o.courtType = s.courtType; if (s.judgmentTypes && s.judgmentTypes.length) o.judgmentTypes = s.judgmentTypes; if (s.referencedRegulation) o.referencedRegulation = s.referencedRegulation; if (s.phrase) o.phrase = s.phrase; }
      if (s.register === "SEJM" || s.register === "EURLEX" || s.register === "RCL" || s.register === "RIP" || s.register === "RIPCASE" || s.register === "DIP" || s.register === "REFE" || s.register === "BAGRSS") o.register = s.register;
      if (s.register === "BAGRSS") o.feed = s.feed;
      if (s.register === "REFE") o.ministry = s.ministry;
      if (s.register === "RIPCASE") o.court = s.court;
      if (s.active === false) o.active = false;
      return o;
    });
}
return out;
}
const out = build(WORKSPACES_PL);
const outDe = build(WORKSPACES_DE);
const header = "// GENERATED by scripts/sync-sources.mjs from app/src/workspaces.js — do not edit.\n// Default per-workspace scan set for the daily cron (see api/scan-all.js).\n";
const body = "module.exports = " + JSON.stringify(out, null, 2).replace(/"([a-z]+)":/g, "$1:") + ";\n";
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "api", "_sources.js");
writeFileSync(target, header + body);
writeFileSync(path.join(path.dirname(target), "..", "server", "php", "sources.json"), JSON.stringify(out, null, 1) + "\n");
writeFileSync(path.join(path.dirname(target), "..", "server", "php", "sources.de.json"), JSON.stringify(outDe, null, 1) + "\n"); // DE set: PHP only, no Vercel counterpart
console.log("DE", Object.fromEntries(Object.entries(outDe).map(([k, v]) => [k, v.length])));
console.log("wrote", target, Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
